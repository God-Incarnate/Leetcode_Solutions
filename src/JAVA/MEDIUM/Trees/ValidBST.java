package JAVA.MEDIUM.Trees;

public class ValidBST {
    //https://leetcode.com/problems/validate-binary-search-tree
    
      public class TreeNode {
          int val;
          TreeNode left;
          TreeNode right;
          TreeNode() {}
          TreeNode(int val) { this.val = val; }
          TreeNode(int val, TreeNode left, TreeNode right) {
              this.val = val;
              this.left = left;
              this.right = right;
          }
      }




}
